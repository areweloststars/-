  const lead = m.match(new RegExp('^~\\s*(?:' + ST_SLOT + '(?=\\s|$)|(?=\\s))\\s*'));
  if (lead && lead[0].length < m.length) { slot = lead[1] || ''; m = m.slice(lead[0].length); }
  m = m.replace(new RegExp('~\\s*' + ST_SLOT + '?', 'g'), (a, p) => stSlot(p, f)).replace(/~/g, '').replace(/\s+/g, ' ').trim();
