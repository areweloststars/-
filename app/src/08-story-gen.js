function stHit(re, text, firstOnly) {
  const s = String(text || '').replace(/[^가-힣\s]/g, ' ').replace(/\s+/g, ' ').trim();
  const y = new RegExp(re.source, 'y');
  for (let p = 0; p < s.length; p = s.indexOf(' ', p) + 1 || s.length) {
    if (firstOnly && p > 0) break;
    y.lastIndex = p;
    const mm = y.exec(s);
    if (!mm || !mm[0]) continue;
    if (mm[0].length >= 2 || AUTO_TAIL.test(s.slice(p + 1).split(' ')[0])) return true;
  }
  return false;
}
