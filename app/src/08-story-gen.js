function mkStory(epWords, rows, n) {
  const f = SF[((n % SF.length) + SF.length) % SF.length];
  const lines = f.intro.map(t => stFill(t, f, null)), words = {}, usedT = new Set();
  const N = epWords.length;
  // 문제가 생기는 단어 → 해결하는 단어 순서로 (같은 자리끼리는 원래 순서)
  const lex = epWords.map((id, i) => ({ id, i, w: stLex(id, rows[id], f) })).sort((a, b) => a.w.stage - b.w.stage || a.i - b.i);
  lex.forEach(({ id, w }, i) => {
    const r = rows[id];
    const own = w.sem ? w.sem[1][w.kind].filter(t => stOk(t, w) && stSlotFits(t, w.slot)) : [];
    const genList = w.kind === 'v' ? (w.sub === 'aux' ? ST_GEN.vaux : ST_GEN.v) : (ST_GEN[w.kind] || ST_GEN.n)[w.sub] || [];
    const gen = genList.filter(t => stOk(t, w));
    const backList = w.kind === 'a' ? ST_GEN.a.other : w.kind === 'd' ? ST_GEN.d.other : w.kind === 'n' ? ST_GEN.n.idea : ST_GEN.v;
    const back = backList.filter(t => stOk(t, w) && !gen.includes(t));
    const start = (n * 7 + i * 3) % Math.max(1, gen.length);
    const order = [...own, ...gen.slice(start), ...gen.slice(0, start), ...back];
    const t = order.find(x => !usedT.has(x)) || order[0] || '{H:은} {Wq:이라는} 말을 수첩에 적었어요.';
    usedT.add(t);
    // 장면 문장은 '~' 자리를 스스로 채우니 앞말을 붙이지 않음
    const prefix = w.slot != null && !own.includes(t) ? stSlot(w.slot, f, stNames(t)) + ' ' : '';
    let line = stFill(t, f, w, prefix);
    // 이음말: 이름으로 시작하는 줄에만, 첫 줄·마지막 줄·가운데 하나 걸러
    const at = i === 0 ? 'first' : i === N - 1 ? 'last' : i % 2 ? 'mid' : '';
    if (at && w.kind !== 'd' && /^\{[HFVPGE]/.test(t) && !/드디어|마침내|그제야|갑자기|그때|결국|끝내|이번에도/.test(t)) {
      const list = ST_OPEN[at]; line = list[(n + i) % list.length] + ' ' + line;
    }
    if (/\}$/.test(line)) line += '.';
    if (lines.includes(line)) line = line.replace(/[.!]?$/, '!');
    lines.push(line);
    // 그림 칸: 뜻 갈래 그림 → 뜻에 맞는 자동 그림 → 주인공 자세
    const hit = (w.sem && w.sem[2]) || (autoPicHit(w.m) || autoPicHit(r.ko) || [])[1] || {};
    let panel;
    if (hit.e) panel = { subject: { kind: 'emoji', emoji: hit.e } };
    else if (hit.a) panel = { subject: { kind: hit.a } };
    else {
      const sj = Object.assign({}, f.hero);
      if (sj.kind === 'person') { sj.pose = hit.p || AUTO_POSE[i % AUTO_POSE.length]; if (hit.face) sj.face = hit.face; }
      else sj.pose = hit.p === 'run' || hit.p === 'sleep' ? hit.p : ['wave', 'cheer', 'hold'][i % 3];
      panel = { subject: sj };
      if (hit.hold) panel.hold = hit.hold;
      else if (!hit.p && i % 2) panel.hold = AUTO_EMO[i % AUTO_EMO.length];
    }
    Object.assign(panel, { bg: f.bg, sign: shortW(id).slice(0, 18), signStyle: panel.subject.kind === 'emoji' ? 'board' : 'bubble', mark: hit.mark || (i % 3 ? 'none' : 'exclaim') });
    const plain = line.replace(/\{[^|}]+\|([^}]+)\}/g, '$1');
    words[id] = { panel, pic: plain.slice(0, 120), tip: mkTip(id, w.m) };
  });
  f.outro.forEach(o => lines.push(stFill(o, f, null)));
  return { title: f.title, lines, words };
}
// 접두사·접미사로 만드는 암기 팁 (뜻과 맞을 때만: 'reluctant'를 re-(다시)로 풀지 않게)
const AFFIX = [
  [/^un[a-z]{3,}/, 'un-(아닌)', m => /않|없|못|불|비|무/.test(m)], [/^mis[a-z]{3,}/, 'mis-(잘못)', m => /잘못|오/.test(m)],
  [/^pre[a-z]{3,}/, 'pre-(미리)', m => /미리|사전|예|전/.test(m)], [/^inter[a-z]{3,}/, 'inter-(사이)', m => /사이|상호|국제|간/.test(m)],
  [/^trans[a-z]{3,}/, 'trans-(가로질러, 옮겨)', m => /옮|전|교통|번역|변/.test(m)], [/^over[a-z]{3,}/, 'over-(넘치게)', m => /과|넘|지나/.test(m)],
  [/^[a-z]{3,}tion$/, '-tion(~하는 것)', m => !/다$/.test(m)], [/^[a-z]{3,}ful$/, '-ful(가득한)', () => true], [/^[a-z]{3,}less$/, '-less(없는)', m => /없|않/.test(m)],
  [/^[a-z]{3,}able$/, '-able(~할 수 있는)', () => true], [/^[a-z]{3,}ly$/, '-ly(~하게)', m => /(게|히|이)$/.test(m)], [/^[a-z]{3,}ness$/, '-ness(~함, 상태)', m => !/다$/.test(m)]
];
function mkTip(en, m) {
  const w = en.toLowerCase();
  if (/\s/.test(w)) return `${w.split(/\s+/).join(' + ')} → 한 덩어리로 외워요: ${m}`;
  const hits = AFFIX.filter(([re, , ok]) => re.test(w) && ok(m)).map(a => a[1]).slice(0, 2);
  return hits.length ? `${hits.join(' + ')} → ${m}` : '';
}

