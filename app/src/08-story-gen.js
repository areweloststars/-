// 단어 하나 분석: 첫 뜻, 품사, 활용 꼴, 문장 갈래
function stLex(id, r, f) {
  const raw = String(r.ko || '');
  const senses = raw.replace(/\([^)]*\)/g, x => x.replace(/[,;/]/g, ' ')).split(/\s*[,;/]\s*/)
    .map(s => s.replace(/\([^)]*\)|\[[^\]]*\]/g, ' ').replace(/[“”"']/g, '').replace(/\s+/g, ' ').trim()).filter(s => /[가-힣]/.test(s));
  let m = senses[0] || raw.replace(/[{}|]/g, '').trim(), slot = null;
  // '~하다' 꼴의 빈자리는 동작 하나로 ('막 ~하려 하다' → '막 도전하려 하다', '~할 수 있다' → '도전할 수 있다')
  m = m.replace(/~\s*(?=(하|해|할|한|했))/g, '도전');
  // 맨 앞 빈자리('~을 고대하다')는 문장을 고른 뒤 이름으로 채움
  const lead = m.match(new RegExp('^~\\s*(?:' + ST_SLOT + '(?=\\s|$)|(?=\\s))\\s*'));
  if (lead && lead[0].length < m.length) { slot = lead[1] || ''; m = m.slice(lead[0].length); }
  m = m.replace(new RegExp('~\\s*' + ST_SLOT + '?', 'g'), (a, p) => stSlot(p, f)).replace(/~/g, '').replace(/\s+/g, ' ').trim();
  let k = koKind(m, id, r.pos);
  let sub = '';
  if (slot != null && (k.kind === 'n' || k.kind === 'd')) {
    const PH = { cause: /(때문에|덕분에|탓에|인해|인하여)$/, concede: /(불구하고|그런데도|하더라도)$/, instead: /(대신에|대신)$/, accord: /(따라|따르면|맞춰|의하면|의해)$/, purpose: /(위해|위하여|위해서)$/, topic: /(대해|관해|대하여|관하여|대해서)$/, compare: /(비해|비하면|달리|반해|보다)$/, with: /(함께|더불어|같이)$/ };
    const hit = Object.keys(PH).find(x => PH[x].test(m));
    if (hit) { k = { kind: 'd' }; sub = 'p_' + hit; }
  }
  const w = { id, m, slot, kind: k.kind, base: m, forms: {}, sub };
  if (k.kind === 'v') {
    w.forms = koVerbForms(k.stem, id);
    // '막 ~하려 하다'·'~할 수 있다' 같은 덩어리는 '-했어요' 꼴만 ('하려 하려다가'처럼 꼬이지 않게)
    if (/(려 하|게 되|게 하|고 있|어 있|아 있|적이 있|수 있|수 없|척하|체하|곤 하|만하|경향이 있|여유가 있|필요가 있|뻔하|줄 알|줄 모르)$/.test(k.stem)) { w.forms = { past: w.forms.past }; w.sub = 'aux'; }
  } else if (k.kind === 'a') {
    w.forms = koAdjForms(k, id); w.base = k.attr;
    const s = k.attr + ' ' + (k.stem || '');
    w.sub = k.pert ? 'pert' : ST_ADJ.trait.test(s) ? 'trait' : ST_ADJ.feel.test(s) ? 'feel' : ST_ADJ.situ.test(s) ? 'situ' : k.jeok ? 'jeok' : /는$/.test(k.attr) && !/(있는|없는)$/.test(k.attr) ? 'act' : 'other';
  } else if (k.kind === 'd') { if (!w.sub) w.sub = Object.keys(ST_ADV).find(x => ST_ADV[x].test(m)) || (/(게|히|이|로)$/.test(m) ? 'manner' : 'other'); }
  else w.sub = koNounKind(m);
  // 뜻 갈래: 낱말 첫머리에서만 찾음. 여러 낱말 형용사('호기심이 많은')는 첫 낱말로, '목적어 + 동사'('영감을 주다')는 첫 낱말에서만
  const multi = /\s/.test(m), light = multi && /^[가-힣]+(을|를|이|가|에|에게|과|와|으로|로)\s/.test(m);
  const semHit = re => k.kind === 'a' ? (multi ? stHit(re, m.split(' ')[0]) : stHit(re, m) || (!!k.attr && k.attr !== m && stHit(re, k.attr))) : stHit(re, m, light);
  w.sem = SEM.find(([re, t]) => (t[k.kind] || []).length && semHit(re)) || null;
  // 이야기 속 자리: 0 문제가 생김 · 1 해 나감 · 2 해결 (문제 → 해결 순서로 이어지게)
  w.stage = stHit(ST_STAGE[0], m) ? 0 : stHit(ST_STAGE[2], m) ? 2 : 1;
  return w;
}
