  // 뜻 갈래: 낱말 첫머리에서만 찾음. 여러 낱말 형용사('호기심이 많은')는 첫 낱말로, '목적어 + 동사'('영감을 주다')는 첫 낱말에서만
  // 그 갈래가 없으면 동사 쪽에서 ('입학을 허가하다' → '허가'). 뒤가 가벼운 동사('연관 짓다', '영감을 주다')는 첫 낱말에서만 ('짓다'를 집 짓기로 보지 않게)
  const multi = /\s/.test(m), light = multi && /^[가-힣]+(을|를|이|가|에|에게|과|와|으로|로)\s/.test(m);
  const lightEnd = multi && /\s(짓다|하다|되다|주다|받다|내다|두다|맺다|시키다|당하다|드리다|보다|쓰다|치다)$/.test(m);
